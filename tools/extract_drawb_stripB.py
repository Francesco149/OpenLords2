#!/usr/bin/env python3
"""
tools/extract_drawb_stripB.py — table extractor for the pass-1 strategic-map
DRAWER-B strip-blitters, BRANCH-B ("strip") path.

These are the kind-3/kind-4/edge-phase siblings of FUN_00453e71 (whose pyramid
branch-A was extracted by extract_drawb_table.py).  All of them share the loop:

    iVar = 0;                          ecx
    src  = param_3 + _DAT_005aeb6c;    esi / iVar2 / pcVar4
    dst  = fb + cursor_x + cursor_y*pitch;   edi / pcVar3 / pcVar5
    [if (param_5 != 2) dst += init_off;]     // 459258 left-edge sliver
    do {
        if (param_4 <= iVar) { <PYRAMID>; break; }   // r2: cmp ebx,ecx; jle
        dst -= pitch;                               // BRANCH B starts here
        <flat strip: dst[OFF] = src[IDX]  (zero-skip)>
        src += stride;  iVar++;
    } while (iVar < count);

r2-VERIFIED (vendor/original/Lords2.exe) for 455f04 @0x455f37, 4580a9 @0x4580dc,
459258 @0x459298: `cmp ebx,ecx; jle <pyramid>` with ebx=param_4=DAT_0056957c
(col_y_accum, 105-300) and ecx=iVar (0..count, count<0xc9 but in practice 3-17).
Since param_4 >> count, the `jle` never fires: the PYRAMID (branch A) is DEAD and
the flat STRIP (branch B) runs exactly `count` times.  So porting branch B is
faithful to the live path.  (Identical reasoning validated the 453e71 port.)

This extractor parses BRANCH B (from the unique `dst = dst + -DAT_004eb274;`
decrement line to `} while`) into a flat table of (src_idx, dst_off) where:

    dst[base - (iVar+1)*pitch + dst_off] = src[src_off2 + iVar*stride + src_idx]

`init_off` (param_5-dependent left shift) and the pcVar4=pcVar3+N aliasing are
folded into dst_off at extraction time, for the param_5=0 (aligned / interior)
variant the strat-terrain1 frame needs.  No depth_k gating — branch B draws the
full strip every row; the diamond shape comes from the dst_off spread plus
zero-skip transparency.

Usage:
    nix develop -c python3 tools/extract_drawb_stripB.py 455f04 4580a9 459258
Writes src/gen/drawb_stripb_<va>.h.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BYADDR = ROOT / "docs/decompiled/by-address"
OUTDIR = ROOT / "src/gen"

# Per-VA config for the param_5=0 (aligned/interior) variant.
#   stride   = source row stride (src += stride per row)
#   init_off = constant added to the dst pointer once before the loop
#              (459258: `if (param_5 != 2) pcVar3 += 0x1c`)
CONFIG = {
    "455f04": dict(stride=0x3a, init_off=0x00, kind=2, phase="3 (left edge)"),
    "456fd8": dict(stride=0x3a, init_off=0x00, kind=2, phase="4 (right edge)"),
    "4580a9": dict(stride=0x1e, init_off=0x00, kind=3, phase="0/1 (aligned)"),
    "459258": dict(stride=0x1e, init_off=0x1c, kind=4, phase="0/1 (aligned)"),
}

DEC_RE = re.compile(r"(\w+) = \1 \+ -DAT_004eb274;")
WHILE_RE = re.compile(r"\}\s*while")
# clean pointer-alias assignment:  pcVar4 = pcVar3;  /  pcVar4 = pcVar3 + 2;
ALIAS_RE = re.compile(
    r"^\s*(\w+)\s*=\s*(\w+)(?:\s*\+\s*(0x[0-9a-fA-F]+|\d+))?\s*;\s*$")
# copy:  *DSTP = SRC;  /  DSTP[OFF] = SRC;
LHS = r"(?:\*(?P<lp>\w+)|(?P<lb>\w+)\[(?P<lo>0x[0-9a-fA-F]+|\d+)\])"
RHS = (r"(?:\*\(char \*\)\((?P<sv>\w+)(?:\s*\+\s*(?P<so>0x[0-9a-fA-F]+|\d+))?\)"
       r"|(?P<sb>\w+)\[(?P<si>0x[0-9a-fA-F]+|\d+)\]"
       r"|\*(?P<sp>\w+))")
COPY_RE = re.compile(rf"^\s*{LHS}\s*=\s*{RHS}\s*;\s*$")


def _num(s):
    if s is None:
        return 0
    return int(s, 16) if s.lower().startswith("0x") else int(s)


def extract(va: str, cfg: dict) -> list[tuple[int, int]]:
    lines = (BYADDR / f"{va}.c").read_text(errors="replace").splitlines()

    # Locate branch B: the unique `dst = dst + -DAT_004eb274;` decrement.
    start = next(i for i, ln in enumerate(lines) if DEC_RE.search(ln))
    dst_base = DEC_RE.search(lines[start]).group(1)
    alias = {dst_base: 0}          # ptr name -> offset relative to dst pointer

    entries = []                   # (src_idx, dst_off)
    for ln in lines[start + 1:]:
        if WHILE_RE.search(ln):
            break
        m = COPY_RE.match(ln)
        if m:
            lp = m.group("lp") or m.group("lb")
            if lp not in alias:
                continue           # writes to a non-dst pointer — shouldn't happen
            lo = _num(m.group("lo"))
            src_idx = _num(m.group("so") if m.group("sv") else m.group("si"))
            dst_off = cfg["init_off"] + alias[lp] + lo
            entries.append((src_idx, dst_off))
            continue
        a = ALIAS_RE.match(ln)
        if a and a.group(2) in alias and "DAT_004eb274" not in ln:
            alias[a.group(1)] = alias[a.group(2)] + _num(a.group(3))
    return entries


def emit_header(va: str, cfg: dict, entries: list[tuple[int, int]]) -> str:
    out = [
        "/* AUTO-GENERATED by tools/extract_drawb_stripB.py from",
        f" * docs/decompiled/by-address/{va}.c — do not edit by hand.",
        " *",
        f" * Pass-1 drawer-B OVERHANG strip-blitter (branch B, view-mode 0,",
        f" * param_5=0) for FUN_00{va} — kind {cfg['kind']}, phase {cfg['phase']}.",
        " * Flat single-row strip replayed once per row (the pyramid branch A is",
        " * dead: param_4=col_y_accum >> count).  Each entry = {src_idx, dst_off}:",
        " *",
        " *   src  = blob + src_off2          (src_off2 = sprite src_off + 900, v0)",
        " *   base = canvas + cursor_x + cursor_y*pitch",
        " *   for (row = 0; row < count; row++)        // row < col_y always",
        " *     dst = base - (row+1)*pitch;",
        " *     for each entry e:",
        f" *       s = src[row*0x{cfg['stride']:x} + e.src_idx];",
        " *       if (s) canvas[dst + e.dst_off] = s;",
        " *",
        f" * init_off (0x{cfg['init_off']:x}) and pcVar4 aliasing folded into dst_off.",
        " */",
        f"#ifndef OPENLORDS2_DRAWB_STRIPB_{va.upper()}_H",
        f"#define OPENLORDS2_DRAWB_STRIPB_{va.upper()}_H",
        "",
        "#include <stdint.h>",
        "",
        "#ifndef OPENLORDS2_DRAWB_FLAT_T_DEFINED",
        "#define OPENLORDS2_DRAWB_FLAT_T_DEFINED",
        "typedef struct { uint16_t src_idx; uint16_t dst_off; } drawb_flat_t;",
        "#endif",
        "",
        f"enum {{ k_drawb_stripb_{va}_stride = 0x{cfg['stride']:x} }};",
        f"static const drawb_flat_t k_drawb_stripb_{va}[] = {{",
    ]
    for (s, d) in entries:
        out.append(f"    {{0x{s:x}, 0x{d:x}}},")
    out.append("};")
    out.append(f"enum {{ k_drawb_stripb_{va}_n = {len(entries)} }};")
    out.append("")
    out.append("#endif")
    return "\n".join(out) + "\n"


def main() -> int:
    if len(sys.argv) < 2:
        sys.exit("usage: extract_drawb_stripB.py <va> [<va> ...]")
    OUTDIR.mkdir(parents=True, exist_ok=True)
    for va in sys.argv[1:]:
        cfg = CONFIG.get(va)
        if not cfg:
            print(f"{va}: no CONFIG entry, skipping")
            continue
        entries = extract(va, cfg)
        if not entries:
            print(f"{va}: NO entries parsed (unexpected shape?)")
            continue
        ss = [s for s, _ in entries]
        ds = [d for _, d in entries]
        print(f"{va}: {len(entries)} copies, stride 0x{cfg['stride']:x}, "
              f"src 0x{min(ss):x}..0x{max(ss):x}, dst 0x{min(ds):x}..0x{max(ds):x}")
        (OUTDIR / f"drawb_stripb_{va}.h").write_text(emit_header(va, cfg, entries))
        print(f"  -> src/gen/drawb_stripb_{va}.h")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
