#!/usr/bin/env python3
"""
tools/extract_drawb_table.py — table extractor for the pass-1 strategic-map
DRAWER-B strip-blitters (the tall-sprite OVERHANG layer; retail FUN_00406673
dispatches them).  These draw the part of a tall terrain sprite (mountain /
blacksmith / lumberjack / cattle / etc.) that rises ABOVE its base diamond
and bleeds into the cells above — the layer drawer A (table_452820) cannot
reach because its offsets are all downward.

Unlike the drawer-A blitters (fixed full-tile copy lists), these are a
sliding-window transparent diamond strip: a `do { … } while (iVar1 < count)`
loop whose first outer iteration unrolls the whole sprite as nested
`if (iVar1 + K < count)` blocks, each adding one source row (+0x3a bytes)
one scanline higher (dst −= pitch).  Per copy `if (src[i]) dst[off] = src[i]`
(zero-skip transparency).

CRITICAL (r2-verified @0x453ea4 `cmp ebx,ecx; jle`): Ghidra decompiles the
outer guard as `if (param_4 <= iVar1)` but the real asm DRAWS when
`iVar1 < param_4` (param_4 = col_y_accum).  The replay loop must use the
corrected sense.  See docs/findings/map-render.md.

This extractor parses the FIRST outer iteration of a 453e71-style blitter
(source via `pcVar2[IDX]` / `*pcVar2`, src advances 0x3a per outer iter,
dst advances −pitch per outer iter) into a table of
`(depth_K, src_lit, dst_lit)` — the literals already bake in the per-row
shear, so the replay only needs depth_K for the `iVar1 + K < count` guard.

Usage:
    nix develop -c python3 tools/extract_drawb_table.py 453e71 [...]
Writes src/gen/drawb_table_<va>.h.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BYADDR = ROOT / "docs/decompiled/by-address"
OUTDIR = ROOT / "src/gen"


def _num(s: str) -> int:
    return int(s, 16) if s.lower().startswith("0x") else int(s)


def extract(va: str) -> dict:
    lines = (BYADDR / f"{va}.c").read_text(errors="replace").splitlines()

    # Stop at the loop epilogue (first `pcVar3 = pcVar3 + -DAT_...` / `+ -`).
    # Depth tracked from `if (iVar1 + N < DAT_005bb478)`; the leading block
    # (before any such guard) is depth 0.
    depth_re = re.compile(r"if \(iVar1 \+ (\w+) < DAT_005bb478\)")
    # `pcVar3[OFF] = pcVar2[IDX];`  /  `pcVar3[OFF] = *pcVar2;`
    #   (also handles `*pcVar3 = ...` → OFF 0)
    copy_re = re.compile(
        r"(?:pcVar3\[(0x[0-9a-fA-F]+|\d+)\]|\*pcVar3)\s*=\s*"
        r"(?:pcVar2\[(0x[0-9a-fA-F]+|\d+)\]|\*pcVar2)\s*;")
    epilogue_re = re.compile(r"pcVar3 = pcVar3 \+ -")

    entries = []          # (depth_K, src_lit, dst_lit)
    depth = 0
    for ln in lines:
        if epilogue_re.search(ln):
            break
        m = depth_re.search(ln)
        if m:
            depth = _num(m.group(1))
        m = copy_re.search(ln)
        if m:
            dst = _num(m.group(1)) if m.group(1) is not None else 0
            src = _num(m.group(2)) if m.group(2) is not None else 0
            entries.append((depth, src, dst))
    return {"va": va, "entries": entries}


def emit_header(info: dict) -> str:
    va = info["va"]
    e = info["entries"]
    out = [
        f"/* AUTO-GENERATED by tools/extract_drawb_table.py from",
        f" * docs/decompiled/by-address/{va}.c — do not edit by hand.",
        " *",
        " * Pass-1 drawer-B tall-sprite OVERHANG strip-blitter table for",
        f" * FUN_00{va} (view-mode 0).  Each entry = {{depth_k, src_off,",
        " * dst_off}}.  Replay (CORRECTED guard — Ghidra inverted it):",
        " *",
        " *   src  = blob + src_off2   (src_off2 = sprite src_off + 900, v0)",
        " *   base = canvas + cursor_x + cursor_y*pitch",
        " *   for (iVar1 = 0; iVar1 < count; iVar1++)",
        " *     if (iVar1 < col_y_accum)            // draws nearly always",
        " *       for each entry e:",
        " *         if (iVar1 + e.depth_k < count)",
        " *           s = src[iVar1*0x3a + e.src_off];",
        " *           if (s) canvas[base - iVar1*pitch + e.dst_off] = s;",
        " *",
        " * src_off/dst_off already bake in the per-row shear; depth_k only",
        " * gates the count window.  0x3a = source row stride.",
        " */",
        f"#ifndef OPENLORDS2_DRAWB_TABLE_{va.upper()}_H",
        f"#define OPENLORDS2_DRAWB_TABLE_{va.upper()}_H",
        "",
        "#include <stdint.h>",
        "",
        "#ifndef OPENLORDS2_DRAWB_COPY_T_DEFINED",
        "#define OPENLORDS2_DRAWB_COPY_T_DEFINED",
        "typedef struct { uint8_t depth_k; uint16_t src_off; uint16_t dst_off; }"
        " drawb_copy_t;",
        "#endif",
        "",
        f"static const drawb_copy_t k_drawb_{va}[] = {{",
    ]
    for (k, s, d) in e:
        out.append(f"    {{{k}, 0x{s:x}, 0x{d:x}}},")
    out.append("};")
    out.append(f"enum {{ k_drawb_{va}_n = {len(e)} }};")
    out.append("")
    out.append("#endif")
    return "\n".join(out) + "\n"


def main() -> int:
    if len(sys.argv) < 2:
        sys.exit("usage: extract_drawb_table.py <va> [<va> ...]")
    OUTDIR.mkdir(parents=True, exist_ok=True)
    for va in sys.argv[1:]:
        info = extract(va)
        e = info["entries"]
        if not e:
            print(f"{va}: NO entries parsed (unexpected blitter shape?)")
            continue
        ks = [k for k, _, _ in e]
        ds = [d for _, _, d in e]
        ss = [s for _, s, _ in e]
        print(f"{va}: {len(e)} copies, depth 0..{max(ks)}, "
              f"src 0x{min(ss):x}..0x{max(ss):x}, dst 0x{min(ds):x}..0x{max(ds):x}")
        (OUTDIR / f"drawb_table_{va}.h").write_text(emit_header(info))
        print(f"  -> src/gen/drawb_table_{va}.h")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
