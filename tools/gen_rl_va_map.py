#!/usr/bin/env python3
"""gen_rl_va_map.py — writes src/rl_va_map.c: retail VA -> the port's rl_<va> function, for the dispatches that call
through a retail code pointer held in data (handler tables, hot-spot actions, menu item actions, dialog callbacks).

Source of truth: rhost's row tables (tools/rhost/rh_hooks*.c). A row enters the map when its adapter is a plain
call of a retail-layout port (rl_<va> / bf_<va>) on argument slots — HOOK_R / HOOK_V / HOOK_SMK* (NAME, N,
rl_<va>(I(0), ...)) — and the table
gives its VA; the map's adapter is the row's (HOOK_R: the port's return; HOOK_V: 0). Rows of old ports (engine_*,
bf_*, mv_*) are left out: rl_ code reaches an old port through its rl_<va> link entry (src/rl_link*.c).

    python3 tools/gen_rl_va_map.py           # rewrite src/rl_va_map.c
    python3 tools/gen_rl_va_map.py --check   # exit 1 if it is stale
"""
import argparse
import glob
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "src", "rl_va_map.c")

ROW = re.compile(r"^(HOOK_(?:SMK_)?[RV]|HOOK_SMK)\((\w+),\s*(\d+),\s*((?:rl|bf)_([0-9a-f]{6}))\(((?:I\(\d+\)(?:, )?)*)\)\)\s*(?:/\*.*\*/\s*)?$", re.M)
TAB = re.compile(r'\{ "(\w+)", (0x[0-9a-f]+)u?,')


def rows():
    out = {}
    for f in sorted(glob.glob(os.path.join(ROOT, "tools", "rhost", "rh_hooks*.c"))):
        s = open(f).read()
        vas = {}
        for m in TAB.finditer(s):
            vas.setdefault(m.group(1), int(m.group(2), 16))
        for m in ROW.finditer(s):
            kind, name, fn, hexva, args = m.group(1), m.group(2), m.group(4), m.group(5), m.group(6)
            va = vas.get(name)
            if va is None or va != int(hexva, 16):
                continue   # an adapter calling another VA's port (a bridge): not this VA's function
            k = len(re.findall(r"I\(", args))
            if va in out:
                continue   # first table wins (as the standalone's thunks)
            out[va] = (kind, fn, k, args)
    return out


def render(m):
    lines = [
        "/* rl_va_map.c — GENERATED by tools/gen_rl_va_map.py from rhost's row tables (tools/rhost/rh_hooks*.c); do not",
        " * edit. Retail VA -> the port's rl_<va> (rl_va.h). An adapter takes the argument slots a[0..]; HOOK_R rows return",
        " * the port's value, HOOK_V rows 0 (as the rows' adapters). */",
        '#include "rl_va.h"',
        '#include "rl.h"',
        '#include "rl_main.h"',
        '#include "rl_io_plat.h"',
        '#include "rl_crt.h"',
        "",
        "#define I(k) ((int)a[k])",
    ]
    for va in sorted(m):
        kind, fn, k, args = m[va]
        call = f"{fn}({args})"
        if kind in ("HOOK_R", "HOOK_SMK", "HOOK_SMK_R"):
            lines.append(f"static uint32_t m_{va:06x}(const uint32_t *a) {{ (void)a; return (uint32_t)({call}); }}")
        else:
            lines.append(f"static uint32_t m_{va:06x}(const uint32_t *a) {{ (void)a; {call}; return 0; }}")
    lines.append("")
    lines.append(f"const rl_va_entry_t rl_va_map[{len(m)}] = {{")
    for va in sorted(m):
        lines.append(f"    {{ 0x{va:06x}u, {m[va][2]}, m_{va:06x} }},")
    lines.append("};")
    lines.append(f"const int rl_va_map_n = {len(m)};")
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = render(rows())
    old = open(OUT).read() if os.path.exists(OUT) else ""
    if a.check:
        if old != text:
            print("src/rl_va_map.c is stale: python3 tools/gen_rl_va_map.py", file=sys.stderr)
            return 1
        return 0
    if old != text:
        open(OUT, "w").write(text)
    print(f"rl_va_map.c: {text.count('    {{ 0x'.replace('{{', '{'))} entries")
    return 0


if __name__ == "__main__":
    sys.exit(main())
