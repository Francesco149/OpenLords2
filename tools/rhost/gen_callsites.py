#!/usr/bin/env python3
"""gen_callsites.py OUT.h — the direct-call (E8) instruction addresses of Lords2.exe's .text, from the IDA export
(all_ida.asm), as a sorted C array: rhost.c's redirect_calls patches a call only at a real call instruction (a raw
byte scan also finds E8 bytes INSIDE other instructions: `mov dword_4EE8E8, 0` at 0x47f41e holds one aimed at
0x47f474). No export: an empty list (redirect_calls falls back to the scan). Derived addresses only — written to
the build dir, never committed."""
import os
import re
import sys

asm = os.path.join(os.environ.get("OL2_EPHEMERAL", "/mnt/ephemeral/openlords2"), "decompiled-ida", "all_ida.asm")
vas = []
if os.path.exists(asm):
    pat = re.compile(r"^([0-9a-f]{8})  call    (\S+)")
    for line in open(asm, errors="replace"):
        m = pat.match(line)
        if m and not re.match(r"(dword|ds:|e[a-ds][xip]|\[|near ptr \[)", m.group(2)):
            vas.append(int(m.group(1), 16))
vas = sorted(set(vas))
with open(sys.argv[1], "w") as f:
    f.write("/* GENERATED by tools/rhost/gen_callsites.py from the IDA export: E8 call instruction VAs */\n")
    f.write(f"static const unsigned int k_callsites_n = {len(vas)}u;\n")
    f.write("static const unsigned int k_callsites[] = {" + ",".join(f"0x{v:x}u" for v in vas or [0]) + "};\n")
print(f"gen_callsites: {len(vas)} call sites")
