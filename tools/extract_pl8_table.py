#!/usr/bin/env python3
"""
tools/extract_pl8_table.py — extract the strategic-map .pl8 bank name/size
table that drives the season loader FUN_004984dc (ported as engine_pl8.c).

Retail keeps a 64-entry table at VA 0x4da050 (stride 0x14): a 16-byte
NUL-padded filename followed by a u32 byte-size (the malloc + raw-read size
passed to the file-read leaf FUN_004af8d9).  The loader indexes it as
`table[bank + offset]` where bank = 0..7 and

    offset = (view_mode==2 ? 0x20 : 0) + (1<=season<=4 ? season*8-8 : 0)

so the 64 entries cover 4 seasonal blocks (1a/1b/1c/1d, offsets 0/8/16/24)
plus a 4-copy view-mode-2 block (offset 0x20, all *2a). Banks 5/6/7
(sprite1a / sprite1b / flags1a) are season-invariant.

Also emits the two trailing single loads from the same function:
misc_cty.pl8 (size at DAT_0x4daec0) and vill_gd8.pl8 (fixed 0x12d8 read).

Usage:  nix develop -c python3 tools/extract_pl8_table.py
Writes src/gen/pl8_table.h.  Reads retail Lords2.exe via r2 (no auto-analysis).
"""
from __future__ import annotations

import os
import struct
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTDIR = ROOT / "src/gen"

TABLE_VA = 0x4DA050
TABLE_N = 64
STRIDE = 0x14
MISC_NAME_VA = 0x4DAEB0
MISC_SIZE_VA = 0x4DAEC0
VILL_NAME_VA = 0x4DBCD4
VILL_SIZE = 0x12D8  # fixed read length in FUN_004984dc


def r2_bytes(exe: str, va: int, n: int) -> bytes:
    out = subprocess.run(
        ["r2", "-q", "-e", "bin.relocs.apply=true",
         "-c", f"p8 {n} @ {va:#x}", exe],
        capture_output=True, text=True, check=True,
    ).stdout
    # keep the last line that is pure hex of the right length
    for ln in reversed(out.splitlines()):
        ln = ln.strip()
        if len(ln) == 2 * n and all(c in "0123456789abcdef" for c in ln):
            return bytes.fromhex(ln)
    raise SystemExit(f"r2 did not return {n} bytes at {va:#x}:\n{out}")


def cstr(b: bytes) -> str:
    z = b.find(b"\0")
    return b[: z if z >= 0 else len(b)].decode("ascii")


def main() -> None:
    gamedir = os.environ.get("OPENLORDS2_GAME_DIR")
    if not gamedir:
        sys.exit("OPENLORDS2_GAME_DIR not set (run inside nix develop)")
    exe = str(Path(gamedir) / "Lords2.exe")
    if not Path(exe).exists():
        sys.exit(f"retail exe not found: {exe}")

    raw = r2_bytes(exe, TABLE_VA, TABLE_N * STRIDE)
    entries = []
    for i in range(TABLE_N):
        rec = raw[i * STRIDE : (i + 1) * STRIDE]
        name = cstr(rec[:16])
        size = struct.unpack_from("<I", rec, 16)[0]
        entries.append((name, size))

    misc_name = cstr(r2_bytes(exe, MISC_NAME_VA, 16))
    misc_size = struct.unpack("<I", r2_bytes(exe, MISC_SIZE_VA, 4))[0]
    vill_name = cstr(r2_bytes(exe, VILL_NAME_VA, 16))

    OUTDIR.mkdir(parents=True, exist_ok=True)
    out = OUTDIR / "pl8_table.h"
    L = []
    L.append("/* AUTO-GENERATED by tools/extract_pl8_table.py from retail")
    L.append(" * Lords2.exe table @0x4da050 — do not edit by hand.")
    L.append(" *")
    L.append(" * Strategic-map .pl8 bank table for the season loader")
    L.append(" * FUN_004984dc (ported as engine_pl8.c).  64 entries, stride")
    L.append(" * 0x14: 16-byte NUL-padded filename + u32 byte-size (the")
    L.append(" * malloc/raw-read length).  Indexed table[bank + offset];")
    L.append(" * offset = (view_mode==2?0x20:0) + (1<=season<=4?season*8-8:0).")
    L.append(" */")
    L.append("#ifndef OPENLORDS2_PL8_TABLE_H")
    L.append("#define OPENLORDS2_PL8_TABLE_H")
    L.append("")
    L.append("#include <stdint.h>")
    L.append("")
    L.append("typedef struct {")
    L.append("    char     name[16];")
    L.append("    uint32_t size;")
    L.append("} Pl8TableEntry;")
    L.append("")
    L.append(f"#define PL8_TABLE_COUNT {TABLE_N}")
    L.append("")
    L.append(f"static const Pl8TableEntry PL8_STRATEGIC_TABLE[{TABLE_N}] = {{")
    for i, (name, size) in enumerate(entries):
        L.append(f'    {{ "{name}", {size}u }}, /* [{i:2d}] */')
    L.append("};")
    L.append("")
    L.append(f'#define PL8_MISC_CTY_NAME "{misc_name}"')
    L.append(f"#define PL8_MISC_CTY_SIZE {misc_size}u")
    L.append(f'#define PL8_VILL_GD8_NAME "{vill_name}"')
    L.append(f"#define PL8_VILL_GD8_SIZE {VILL_SIZE}u")
    L.append("")
    L.append("#endif /* OPENLORDS2_PL8_TABLE_H */")
    out.write_text("\n".join(L) + "\n")
    print(f"wrote {out} ({TABLE_N} entries; "
          f"misc={misc_name}/{misc_size} vill={vill_name}/{VILL_SIZE:#x})")


if __name__ == "__main__":
    main()
